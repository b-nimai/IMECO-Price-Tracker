# Builds the distributable .exe.
#
#   cd desktop
#   ./build.ps1
#
# Output: desktop/dist/IMECO Price Tracker.exe — a single file needing no Python install on
# the machine it runs on.
#
# If ../.env holds the Supabase credentials they are baked into the build, so the .exe runs on
# a staff PC without a first-launch setup prompt. They are written to desktop/_baked.py just
# before PyInstaller runs and deleted immediately after, so they never sit in the working tree
# waiting to be committed. Without a ../.env the build still succeeds and the app falls back to
# prompting and storing in Windows Credential Manager.
#
# A baked service_role key is recoverable from the .exe. These builds are for IMECO staff only;
# if one leaves the company, rotate the key in Supabase -> Project Settings -> API.

# "Continue", not "Stop", and that is deliberate. Under Windows PowerShell 5.1 anything a
# native .exe writes to stderr is re-raised as a NativeCommandError, so with "Stop" a single
# PyInstaller WARNING (it emits one about conda-meta on every venv build) aborts a build that
# was about to succeed. Every native call below is checked on $LASTEXITCODE instead, which is
# the only signal that actually means failure.
$ErrorActionPreference = "Continue"
Set-Location $PSScriptRoot

# ── Why an isolated environment, and not just the interpreter on PATH ────────────────────
#
# PyInstaller bundles what it can reach. Built from the conda base environment this produced a
# 223 MB executable: numpy, matplotlib, PyQt6, IPython, jedi, zmq, lxml, sqlite and the whole
# MKL stack came along, because they were installed, not because anything here imports them.
#
# A throwaway venv holding only requirements.txt is the fix, and it is also the only way the
# build is reproducible — otherwise the size and contents of the .exe depend on whatever the
# person building it happens to have installed.
$venv = Join-Path $PSScriptRoot ".buildenv"
$py = Join-Path $venv "Scripts\python.exe"

if (-not (Test-Path $py)) {
  Write-Host "Creating an isolated build environment..." -ForegroundColor Cyan
  python -m venv $venv
  if ($LASTEXITCODE -ne 0) { throw "could not create the build venv" }
}

Write-Host "Installing build dependencies..." -ForegroundColor Cyan
& $py -m pip install --quiet --upgrade pip
& $py -m pip install --quiet --upgrade -r requirements.txt
if ($LASTEXITCODE -ne 0) { throw "dependency install failed" }

# The real pricing sheet is deliberately NOT in git — this repo is public and that file is
# IMECO's pricing strategy. A fresh clone therefore has only the example, which is enough to
# produce a working .exe: it starts up, and the operator points it at the real sheet through
# the Spreadsheet button. Building against the real sheet, when present, just saves them a step.
$sheet = Join-Path $PSScriptRoot "..\Docs\pricing link.xlsx"
if (-not (Test-Path $sheet)) {
  $sheet = Join-Path $PSScriptRoot "..\Docs\pricing link.example.xlsx"
  Write-Host "No Docs/pricing link.xlsx - bundling the example sheet instead." -ForegroundColor Yellow
  Write-Host "The operator supplies the real one via the app's Spreadsheet button." -ForegroundColor Gray
}
if (-not (Test-Path $sheet)) { throw "no workbook to bundle: $sheet" }

# ── Baking the Supabase secrets into the build ───────────────────────────────────────────
#
# Without this the .exe prompts for SUPABASE_URL and SUPABASE_SERVICE_KEY on a machine whose
# Credential Manager has never seen them, which is every machine it is copied to. So the
# values from ../.env are written into desktop/_baked.py, PyInstaller picks that module up,
# and the `finally` at the bottom deletes it again — it exists only for the duration of a
# build and is never left in the working tree for `git commit -a` to find. It is also in
# .gitignore, as a second line of defence.
#
# The trade-off is real and worth stating: a baked service_role key can be recovered from the
# .exe with `strings`. Builds made this way are for IMECO staff only. If one ever gets out,
# rotate the key in Supabase -> Project Settings -> API.
$baked = Join-Path $PSScriptRoot "_baked.py"
$envFile = Join-Path $PSScriptRoot "..\.env"

if (Test-Path $envFile) {
  $vals = @{}
  foreach ($line in (Get-Content $envFile)) {
    $t = $line.Trim()
    if ($t -and -not $t.StartsWith("#") -and $t.Contains("=")) {
      $k, $v = $t.Split("=", 2)
      $vals[$k.Trim()] = $v.Trim().Trim('"').Trim("'")
    }
  }
  $url = $vals["SUPABASE_URL"]
  $key = $vals["SUPABASE_SERVICE_KEY"]

  if ($url -and $key) {
    # Written as a repr-safe Python literal. Values are quoted with ' and any embedded quote
    # or backslash escaped, so a key containing either cannot break out of the string.
    function Esc($s) { $s.Replace("\", "\\").Replace("'", "\'") }
    @(
      "# GENERATED BY build.ps1 - DO NOT COMMIT, DO NOT EDIT."
      "# Deleted automatically when the build finishes. See build.ps1 and config.py."
      "SUPABASE_URL = '$(Esc $url)'"
      "SUPABASE_SERVICE_KEY = '$(Esc $key)'"
    ) | Set-Content -Path $baked -Encoding utf8
    Write-Host "Baking Supabase credentials from .env into this build." -ForegroundColor Yellow
    Write-Host "The .exe will run without a setup prompt - keep it internal." -ForegroundColor Gray
  } else {
    Write-Host "..\.env has no SUPABASE_URL / SUPABASE_SERVICE_KEY - not baking." -ForegroundColor Yellow
  }
} else {
  Write-Host "No ..\.env found - the .exe will prompt for credentials on first launch." -ForegroundColor Yellow
}

Write-Host "Building..." -ForegroundColor Cyan
try {

# --windowed suppresses the console; the GUI is the interface. The scheduled task runs the
# same binary with --silent, which takes the headless path in app.py.
#
# The workbook is bundled as the STARTING sheet, not the only one: a fresh .exe works on a
# machine that has never seen the spreadsheet, and the operator can then swap in a newer one
# through the Spreadsheet button, which stores it in %LOCALAPPDATA% and takes precedence from
# the next run onward. So editing the sheet no longer requires a rebuild — see
# catalogue.active_workbook().
#
# The excludes are belt-and-braces for the venv above. If someone builds with the system
# interpreter anyway, these keep the worst offenders out.
$pyiArgs = @(
  "--onefile"
  "--windowed"
  "--clean"
  "--noconfirm"
  "--name", "IMECO Price Tracker"
  "--add-data", "$sheet;Docs"
  # PyInstaller only puts the ENTRY SCRIPT's own directory on its analysis path. That
  # directory is desktop\, from which `import desktop.app` is invisible — every module here
  # was collected as a loose top-level module and the frozen .exe died at startup with
  # "No module named 'desktop.app'". Adding the repo root makes the package itself
  # importable, which is what every `from .x import y` in this codebase actually needs.
  "--paths", (Join-Path $PSScriptRoot "..")
  "--hidden-import", "keyring.backends.Windows"
  "--exclude-module", "numpy"
  "--exclude-module", "matplotlib"
  "--exclude-module", "PyQt5"
  "--exclude-module", "PyQt6"
  "--exclude-module", "PySide6"
  "--exclude-module", "IPython"
  "--exclude-module", "jedi"
  "--exclude-module", "zmq"
  "--exclude-module", "lxml"
  "--exclude-module", "PIL"
  "--exclude-module", "pandas"
  "--exclude-module", "scipy"
  "--exclude-module", "pytest"
  "desktop_entry.py"
)

# `from . import _baked` sits inside a try/except that the analyser cannot follow, so the
# module has to be named explicitly - but only when it exists. A hidden import that resolves
# to nothing is a hard error, so a build without ..\.env must not ask for it.
if (Test-Path $baked) {
  $pyiArgs = @("--hidden-import", "desktop._baked") + $pyiArgs
}

& $py -m PyInstaller @pyiArgs

if ($LASTEXITCODE -ne 0) { throw "PyInstaller failed" }
}
finally {
  # The whole point of the exercise: the secrets live on disk only while PyInstaller reads
  # them. This runs on success, on failure, and on Ctrl-C, so a broken build cannot leave a
  # credential file behind. __pycache__ is cleared too — a .pyc holds the same strings.
  if (Test-Path $baked) {
    Remove-Item $baked -Force
    Write-Host "Removed desktop\_baked.py - no credentials left in the working tree." -ForegroundColor Cyan
  }
  Get-ChildItem (Join-Path $PSScriptRoot "__pycache__") -Filter "_baked.*" -ErrorAction SilentlyContinue |
    Remove-Item -Force -ErrorAction SilentlyContinue
}

$exe = Join-Path $PSScriptRoot "dist\IMECO Price Tracker.exe"
$size = [math]::Round((Get-Item $exe).Length / 1MB, 1)
Write-Host "`nBuilt: $exe ($size MB)" -ForegroundColor Green
